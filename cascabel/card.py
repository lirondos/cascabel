"""Profile and output cards: standardized documentation artifacts.

A **dataset profile card** documents what a gold-standard split looks like
along cascabel's dimensions; a **performance profile card** additionally documents
how one system's predictions behave on it (scores, error taxonomy,
per-dimension performance). Cards are plain, versioned markdown generated
entirely from the data — the documentation analogue of model cards and
datasheets, for sequence-labeling evaluations.
"""

from __future__ import annotations

import datetime
from pathlib import Path
from typing import Optional, Union

from cascabel.report import SCORE_GLOSSES, SHAPE_LISTS, SHAPE_NOTE, gloss, identity_rows

#: Below this share of applicable entities a dimension is reported as n/a.
APPLICABILITY_FLOOR = 25.0
#: Below this many gold entities, percentages are flagged as noisy.
SMALL_TEST_FLOOR = 2000
#: Below this many gold spans, a dimension's scores are flagged as noisy.
SMALL_DIMENSION_FLOOR = 30


def _ci(interval) -> str:
    if interval is None:
        return ""
    return f" [{interval['lo']:.3f}, {interval['hi']:.3f}]"


def _score_row(name, data, interval=None):
    return (f"| {name} | {data['precision']:.4f} | {data['recall']:.4f} | "
            f"{data['f1']:.4f}{_ci(interval)} | "
            f"{data['tp']}/{data['fp']}/{data['fn']} |")


def build_card(
    casc,
    dataset: str = "unspecified",
    split: str = "test",
    system: Optional[str] = None,
    notes: Optional[str] = None,
    ci: Optional[dict] = None,
) -> str:
    """Render a profile card (no prediction) or output card (prediction).

    ``ci`` is an optional bootstrap-CI dict (from ``Cascabel.bootstrap()``);
    when given, 95%-style intervals are appended to the F1 columns.
    """
    from cascabel import __version__

    ci = ci or {}
    report = casc.report()
    has_system = casc.prediction is not None
    kind = "Performance Profile Card" if has_system else "Dataset Profile Card"
    today = datetime.date.today().isoformat()
    caveats = []

    lines = [f"# {kind}", ""]
    lines.append(f"| | |")
    lines.append(f"|---|---|")
    lines.append(f"| **Dataset** | {dataset} ({split} split) |")
    if has_system:
        lines.append(f"| **System** | {system or 'unspecified'} |")
    lines.append(f"| **Generated by** | cascabel {__version__}, {today} |")
    lines.append("")

    data = report["dataset"]
    labels = ", ".join(f"{k} ({v})" for k, v in sorted(data["labels"].items()))
    lines += ["## Composition", "",
              f"{data['tokens']} tokens · {data['sentences']} sentences · "
              f"{data['entities']} entities · labels: {labels or 'none'}", ""]
    if data["entities"] < SMALL_TEST_FLOOR:
        caveats.append(
            f"Small evaluation set ({data['entities']} entities): dimension "
            "percentages and per-dimension scores carry sampling noise.")

    lines += ["| dimension | meaning | % of entities | applicability |",
              "|---|---|---|---|"]
    for name, stats in report["dimensions"].items():
        if stats["applicability"] < APPLICABILITY_FLOOR:
            lines.append(f"| {name} | {gloss(name)} | n/a | {stats['applicability']:.0f}% |")
            caveats.append(
                f"Dimension `{name}` is inapplicable for "
                f"{100 - stats['applicability']:.0f}% of entities "
                "(e.g. caseless script) and is reported as n/a.")
        else:
            lines.append(f"| {name} | {gloss(name)} | {stats['percentage']:.1f}% | "
                         f"{stats['applicability']:.0f}% |")
    lines.append("")

    if "identity" in report:
        lines += ["## Identity (test spans vs training)", "",
                  "| measure | count | share |", "|---|---|---|"]
        lines += [f"| {name} | {part} / {whole} | "
                  f"{'n/a' if share is None else f'{100 * share:.1f}%'} |"
                  for name, part, whole, share in identity_rows(report["identity"])]
        lines.append("")

    if "shape" in report:
        shape = report["shape"]
        lines += ["## Shape", "", SHAPE_NOTE, "",
                  "| label | " + " | ".join(title for _, title in SHAPE_LISTS) + " |",
                  "|---|---|---|"]
        for label, lists in shape.items():
            cells = " | ".join(", ".join(f"*{t}*" for t in lists[key])
                               for key, _ in SHAPE_LISTS)
            lines.append(f"| {label} | {cells} |")
        lines.append("")

    if casc.training is None:
        caveats.append("No training split provided: exposure dimensions "
                       "(unseen, seen with same/ambiguous/other label) and shape "
                       "scores are unavailable.")

    if has_system:
        ci_note = (" (F1 with 95% bootstrap CI)" if ci else "")
        lines += ["## Metrics" + ci_note, "",
                  "| view | P | R | F1 | tp/fp/fn |", "|---|---|---|---|---|"]
        for view in ("span", "token", "boundary"):
            lines.append(_score_row(view, report["scores"][view], ci.get(view)))
        lines.append("")
        lines += [f"- **{name}**: {text}" for name, text in SCORE_GLOSSES.items()]
        lines.append("")
        if report["scores_by_label"]:
            lines += ["| label | P | R | F1 | tp/fp/fn |",
                      "|---|---|---|---|---|"]
            for label, s in report["scores_by_label"].items():
                lines.append(_score_row(label, s))
            lines.append("")

        errors = report["error_counts"]
        total = sum(errors.values())
        lines += ["## Error profile", "",
                  f"{total} errors "
                  f"({report['diagnostics']['retrieval_capacity']:.3f} "
                  "retrieval capacity, "
                  f"{report['diagnostics']['noise_level']:.4f} noise level)",
                  "", "| error type | count | share |", "|---|---|---|"]
        for error_type, count in sorted(errors.items(), key=lambda i: -i[1]):
            lines.append(f"| {error_type} | {count} | "
                         f"{100 * count / total:.1f}% |" if total else
                         f"| {error_type} | 0 | – |")
        lines.append("")

        header = "| dimension | F1 | P | R | n (tp+fn) |"
        if ci:
            header = "| dimension | F1 [95% CI] | P | R | n (tp+fn) |"
        lines += ["## Disaggregated evaluation", "", header,
                  "|---|---|---|---|---|"]
        small = []
        for name, s in report.get("scores_by_dimension", {}).items():
            stats = report["dimensions"].get(name)
            if stats and stats["applicability"] < APPLICABILITY_FLOOR:
                continue
            n_gold = s["tp"] + s["fn"]
            if n_gold < SMALL_DIMENSION_FLOOR:
                small.append(f"`{name}` (n={n_gold})")
            lines.append(f"| {name} | {s['f1']:.4f}{_ci(ci.get(name + '.f1'))} | "
                         f"{s['precision']:.4f} | {s['recall']:.4f} | {n_gold} |")
        lines.append("")
        if small:
            caveats.append(
                f"Fewer than {SMALL_DIMENSION_FLOOR} gold spans in "
                f"{', '.join(small)}: their scores are too noisy to interpret.")

    lines += ["## Caveats and recommendations", ""]
    lines += [f"- {c}" for c in caveats] or ["- none detected"]
    if notes:
        lines += ["", "## Notes", "", notes]
    lines += ["", "---", f"*Card schema v1 — generated automatically by "
              f"[cascabel](https://pypi.org/project/cascabel-ner/) {__version__}.*",
              ""]
    return "\n".join(lines)


def write_card(casc, path: Union[str, Path], **metadata) -> Path:
    path = Path(path)
    path.write_text(build_card(casc, **metadata), encoding="utf-8")
    return path
